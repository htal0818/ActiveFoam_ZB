@njit(cache=True, inline="always")
def _local_inplace(out, bs, shear):
    for j in range(1, len(out)):
        ny = np.rint((out[j,1]-out[j-1,1])/bs)
        out[j,1] -= ny*bs
        out[j,0] -= ny*bs*shear
        out[j,0] -= np.rint((out[j,0]-out[j-1,0])/bs)*bs


@njit(cache=True)
def local(points, bs, shear):
    out = points.copy()
    _local_inplace(out, bs, shear)
    return out


@njit(cache=True)
def resample(mid, spacing):
    lengths = np.sqrt(np.sum((mid[1:]-mid[:-1])**2,axis=1))
    total = lengths.sum()
    n = int(np.floor(total/spacing))
    out = np.empty((n+2,2))
    out[0],out[-1] = mid[0],mid[-1]
    if n:
        cum = np.empty(len(mid));cum[0]=0.
        for i in range(len(lengths)): cum[i+1] = cum[i]+lengths[i]/total
        for i in range(n):
            t = (i+1)/(n+1)
            k = min(max(np.searchsorted(cum,t,side='right')-1,0),len(lengths)-1)
            f = (t-cum[k])/(cum[k+1]-cum[k]+1e-30)
            out[i+1] = mid[k]+f*(mid[k+1]-mid[k])
    return out,n


@njit(cache=True)
def advance(vpos, ends, faces, tension, mids, areas, centers, bs, shear,
            psi, dt, pressure, lsc, spacing, outward=None):
    force = np.zeros_like(vpos)
    new = List()
    for e in range(len(mids)):
        mid = mids[e]; f = np.zeros_like(mid)
        f0,f1 = faces[e]
        pn = 0.
        if f0 >= 0: pn -= pressure*(lsc*lsc/areas[f0]-1.)/lsc
        if f1 >= 0: pn += pressure*(lsc*lsc/areas[f1]-1.)/lsc
        center = centers[f1]
        teff = max(0.,tension[e])
        for j in range(len(mid)-1):
            dx = mid[j+1,0] - mid[j,0]
            dy = mid[j+1,1] - mid[j,1]
            length = np.hypot(dx,dy)
            if length < 1e-14: continue
            tx,ty = dx/length,dy/length
            nx,ny = -ty,tx
            if outward is None:
                mx = .5*(mid[j+1,0]+mid[j,0])-center[0]
                my = .5*(mid[j+1,1]+mid[j,1])-center[1]
                wrap = np.rint(my/bs); my -= wrap*bs; mx -= wrap*bs*shear
                mx -= np.rint(mx/bs)*bs
                if nx*mx+ny*my < 0: nx,ny = -nx,-ny
            else:
                nx,ny = nx*outward[e],ny*outward[e]
            normal = pn*length/2.
            f[j,0] += teff*tx+normal*nx
            f[j,1] += teff*ty+normal*ny
            f[j+1,0] += -teff*tx+normal*nx
            f[j+1,1] += -teff*ty+normal*ny
        for axis in range(2):
            force[ends[e,0],axis] += f[0,axis]
            force[ends[e,1],axis] += f[-1,axis]
        new.append(mid+psi*dt*f)
    vertices = vpos+psi*dt*force
    counts = np.empty(len(mids),np.int64)
    for e in range(len(new)):
        mid = new[e]
        for axis in range(2):
            mid[0,axis] = vertices[ends[e,0],axis]
            mid[-1,axis] = vertices[ends[e,1],axis]
        _local_inplace(mid,bs,shear)
        total = 0.
        minimum = np.inf
        maximum = -np.inf
        for j in range(len(mid)-1):
            dx = mid[j+1,0] - mid[j,0]
            dy = mid[j+1,1] - mid[j,1]
            length = np.sqrt(dx*dx + dy*dy)
            total += length
            minimum = np.minimum(minimum, length)
            maximum = np.maximum(maximum, length)
        n = len(mid)-2
        if (total < spacing*(n-1/3) or total > spacing*(n+4/3)
                or maximum/max(minimum,1e-12)>2):
            mid,n = resample(mid,spacing)
        new[e]=mid;counts[e]=n
    return vertices,new,counts


@njit(cache=True)
def face_geometry(mids, face_edges, bs, shear):
    areas = np.empty(len(face_edges)); centers = np.empty((len(face_edges),2))
    for c in range(len(face_edges)):
        edges = face_edges[c]; n = 0
        for se in edges:
            e = se if se>=0 else -se-1
            n += len(mids[e])-1
        points = np.empty((n,2)); k=0
        for se in edges:
            e = se if se>=0 else -se-1
            mid = mids[e]
            for j in range(len(mid)-1):
                points[k] = mid[j] if se>=0 else mid[len(mid)-1-j]
                k+=1
        _local_inplace(points,bs,shear)
        a=0.;cx=0.;cy=0.
        for j in range(n):
            q=(j+1)%n
            a += points[j,0]*points[q,1]-points[q,0]*points[j,1]
            cx+=points[j,0];cy+=points[j,1]
        areas[c]=a*.5
        cx/=n;cy/=n
        wrap=np.floor(cy/bs);cy-=wrap*bs;cx-=wrap*bs*shear
        centers[c,0]=(cx-shear*cy)%bs+shear*cy
        centers[c,1]=cy
    return areas,centers

@njit(cache=True, inline="always")
def _intersection_parameter(p, q, i, j, dx, dy):
    ex = q[j+1, 0] - q[j, 0]
    ey = q[j+1, 1] - q[j, 1]
    det = dx*ey - dy*ex
    if abs(det) < 1e-15:
        return -1.
    rx = q[j, 0] - p[i, 0]
    ry = q[j, 1] - p[i, 1]
    u = (rx*dy - ry*dx)/det
    t = (rx*ey - ry*ex)/det
    return t if 0. < u < 1. and 0. < t < 1. else -1.


@njit(cache=True)
def crossings(p, q, skip_i=-1, skip_j=-1):
    points = []
    ii = []; jj = []
    for i in range(len(p)-1):
        dx = p[i+1, 0] - p[i, 0]
        dy = p[i+1, 1] - p[i, 1]
        for j in range(len(q)-1):
            if i == skip_i and j == skip_j: continue
            t = _intersection_parameter(p, q, i, j, dx, dy)
            if t > 0.:
                points.append(p[i]+t*(p[i+1]-p[i]));ii.append(i);jj.append(j)
    return points,ii,jj


@njit(cache=True)
def _crossing_count(p, q, limit, skip_i=-1, skip_j=-1):
    count = 0
    for i in range(len(p)-1):
        dx = p[i+1, 0] - p[i, 0]
        dy = p[i+1, 1] - p[i, 1]
        for j in range(len(q)-1):
            if i == skip_i and j == skip_j:
                continue
            if _intersection_parameter(p, q, i, j, dx, dy) > 0.:
                count += 1
                if count == limit:
                    return count
    return count


@njit(cache=True)
def adjacent_vertices(mids, ends, incidences, bs, shear):
    result=[]
    for v in range(len(incidences)):
        es=[int(e) for e in incidences[v] if e>=0]
        for k in range(len(es)):
            ea,eb=es[k],es[(k+1)%len(es)]
            if ea==eb or (ends[ea,0]==ends[eb,0] and ends[ea,1]==ends[eb,1]):continue
            p,q=mids[ea],mids[eb];n=len(p)
            # The only segment pair is the skipped pair at the shared vertex.
            if n == 2 and len(q) == 2:
                continue
            both=local(np.vstack((p,q)),bs,shear)
            i=0 if ends[ea,0]==v else len(p)-2
            j=0 if ends[eb,0]==v else len(q)-2
            if _crossing_count(both[:n],both[n:],2,i,j) == 1:
                result.append(v);break
    return result


@njit(cache=True)
def edge_bounds(mids):
    bounds = np.empty((len(mids), 4))
    for e, points in enumerate(mids):
        x0 = x1 = points[0, 0]
        y0 = y1 = points[0, 1]
        for i in range(1, len(points)):
            x, y = points[i]
            x0, x1 = min(x0, x), max(x1, x)
            y0, y1 = min(y0, y), max(y1, y)
        bounds[e, 0] = x0
        bounds[e, 1] = x1
        bounds[e, 2] = y0
        bounds[e, 3] = y1
    return bounds


@njit(cache=True)
def lens_edges(mids, ends, faces, bs, shear):
    result = np.zeros(len(ends), np.bool_)
    free_edges = np.flatnonzero((faces[:, 0] == -1) & (faces[:, 1] >= 0))
    if len(free_edges) < 2:
        return result
    # Two straight films can intersect at most once. Keep the original
    # ordering of all pairs that can form the two-intersection lens.
    curved = np.array([e for e in free_edges if len(mids[e]) > 2], dtype=np.int64)
    if not len(curved):
        return result
    bounds = edge_bounds(mids)
    for i, a in enumerate(free_edges):
        cx0,cx1,cy0,cy1=bounds[a]
        candidates = free_edges[i+1:] if len(mids[a]) > 2 else curved[np.searchsorted(curved,a,side='right'):]
        for b in candidates:
            if faces[b,1]==faces[a,1]:continue
            if (ends[a,0]==ends[b,0] or ends[a,0]==ends[b,1] or
                ends[a,1]==ends[b,0] or ends[a,1]==ends[b,1]):continue
            x0,x1,y0,y1=bounds[b]
            sy=bs*np.rint((y0-cy0)/bs)
            if y1-sy<cy0 or y0-sy>cy1:continue
            sx=sy*shear+bs*np.rint((x0-sy*shear-cx0)/bs)
            if x1-sx<cx0 or x0-sx>cx1:continue
            p,q=mids[a],mids[b];n1=len(p)
            both=local(np.vstack((p,q)),bs,shear)
            if _crossing_count(both[:n1],both[n1:],3) == 2:
                result[a]=True;result[b]=True
    return result


@njit(cache=True)
def polygon_centroids(mids, loops, bs, shear):
    centers = np.empty((len(loops), 2))
    for face, loop in enumerate(loops):
        size = 0
        for e in loop:
            size += len(mids[e if e >= 0 else -e-1]) - 1
        points = np.empty((size, 2))
        k = 0
        for e in loop:
            mid = mids[e if e >= 0 else -e-1]
            for j in range(len(mid)-1):
                points[k] = mid[j] if e >= 0 else mid[len(mid)-1-j]
                k += 1
        points = local(points, bs, shear)
        twice_area = 0.
        cx = cy = 0.
        x0, y0 = points[0]
        for i in range(size):
            j = (i+1) % size
            x, y = points[i, 0] - x0, points[i, 1] - y0
            nx, ny = points[j, 0] - x0, points[j, 1] - y0
            cross = x*ny - y*nx
            twice_area += cross
            cx += (x+nx)*cross
            cy += (y+ny)*cross
        cx = x0 + cx/(3*twice_area)
        cy = y0 + cy/(3*twice_area)
        wrap = np.floor(cy/bs)
        cy -= wrap*bs
        cx -= wrap*bs*shear
        centers[face, 0] = (cx-shear*cy) % bs + shear*cy
        centers[face, 1] = cy
    return centers


@njit(cache=True)
def cell_perimeters(mids, loops):
    edge_lengths = lengths(mids)
    perimeters = np.zeros(len(loops))
    for face, loop in enumerate(loops):
        for e in loop:
            perimeters[face] += edge_lengths[e if e >= 0 else -e-1]
    return perimeters


@njit(cache=True)
def shear_component(mids, tensions):
    total = 0.
    for e, points in enumerate(mids):
        tension = tensions[e]
        if tension <= 0.:
            continue
        subtotal = 0.
        for i in range(len(points)-1):
            dx = points[i+1, 0] - points[i, 0]
            dy = points[i+1, 1] - points[i, 1]
            length = np.hypot(dx, dy)
            if length > 1e-12:
                subtotal += tension*dx*dy/length
        total += subtotal
    return total

@njit(cache=True)
def self_crosses(points):
    n=len(points)
    for i in range(n):
        a,b=points[i],points[(i+1)%n]
        dx,dy=b-a
        for j in range(i+2,n):
            if i==0 and j==n-1:continue
            c,d=points[j],points[(j+1)%n]
            ex,ey=d-c;det=dx*ey-dy*ex
            if abs(det)<1e-15:continue
            rx,ry=c-a
            u=(rx*dy-ry*dx)/det;t=(rx*ey-ry*ex)/det
            if 1e-12<u<1-1e-12 and 1e-12<t<1-1e-12:return True
    return False


@njit(cache=True)
def lengths(mids):
    out=np.empty(len(mids))
    for e in range(len(mids)):
        total=0.
        mid = mids[e]
        for j in range(len(mid)-1):
            dx = mid[j+1,0]-mid[j,0]
            dy = mid[j+1,1]-mid[j,1]
            total+=np.hypot(dx,dy)
        out[e]=total
    return out

@njit(cache=True)
def crossing_depth(points, vertices, bs, shear):
    """Maximum crossing-to-junction distance; distinguishes sub-threshold folds."""
    n=len(points);maximum=0.;count=0
    for i in range(n):
        a,b=points[i],points[(i+1)%n];dx,dy=b-a
        for j in range(i+2,n):
            if i==0 and j==n-1:continue
            c,d=points[j],points[(j+1)%n];ex,ey=d-c;det=dx*ey-dy*ex
            if abs(det)<1e-15:continue
            rx,ry=c-a;u=(rx*dy-ry*dx)/det;t=(rx*ey-ry*ex)/det
            if 1e-12<u<1-1e-12 and 1e-12<t<1-1e-12:
                p=a+t*(b-a);nearest=np.inf
                for v in vertices:
                    vx,vy=p-v;k=np.rint(vy/bs);vy-=k*bs;vx-=k*bs*shear;vx-=np.rint(vx/bs)*bs
                    nearest=min(nearest,np.hypot(vx,vy))
                maximum=max(maximum,nearest);count+=1
    return count,maximum


