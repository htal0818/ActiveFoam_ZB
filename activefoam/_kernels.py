@njit(cache=True)
def signed_cell_edges(vertices, incidences, endpoints, neighbors, cell):
    signed = np.empty(len(vertices), dtype=np.int64)
    for k, a in enumerate(vertices):
        b = vertices[(k + 1) % len(vertices)]
        for e in incidences[a]:
            if e < 0:
                continue
            x, y = endpoints[e]
            if not ((x == a and y == b) or (x == b and y == a)):
                continue
            if cell != neighbors[e, 0] and cell != neighbors[e, 1]:
                continue
            used = False
            for j in range(k):
                edge = signed[j] if signed[j] >= 0 else -signed[j] - 1
                if edge == e:
                    used = True
                    break
            if not used:
                signed[k] = e if x == a and y == b else -e - 1
                break
        else:
            return signed[:0]
    return signed


@njit(cache=True)
def shrinking_boundary_candidates(edges, previous, length, endpoints, incidence, threshold):
    result = np.zeros(len(edges), np.bool_)
    neighbors = np.empty(4, dtype=np.int64)
    for k, edge in enumerate(edges):
        if length[edge] >= threshold or length[edge] >= previous[edge]:
            continue
        a, b = endpoints[edge]
        count = 0
        for vertex in (a, b):
            for incident in incidence[vertex]:
                if incident < 0:
                    continue
                for other in endpoints[incident]:
                    if other == a or other == b:
                        continue
                    if other in neighbors[:count]:
                        continue
                    if count == 4:
                        count = 5
                        break
                    neighbors[count] = other
                    count += 1
                if count == 5:
                    break
            if count == 5:
                break
        result[k] = count == 4
    return result


@njit(cache=True)
def finite_films(mids):
    for points in mids:
        for row in points:
            if not (np.isfinite(row[0]) and np.isfinite(row[1])):
                return False
    return True


@njit(cache=True)
def cell_crossing_report(mids, loops, positions, junctions, bs, shear):
    total = 0
    maximum = 0.
    for cell, loop in enumerate(loops):
        size = 0
        for signed in loop:
            size += len(mids[signed if signed >= 0 else -signed - 1]) - 1
        points = np.empty((size, 2))
        index = 0
        for signed in loop:
            line = mids[signed if signed >= 0 else -signed - 1]
            for j in range(len(line) - 1):
                row = j if signed >= 0 else len(line) - 1 - j
                points[index, 0] = line[row, 0]
                points[index, 1] = line[row, 1]
                index += 1
        _local_inplace(points, bs, shear)
        if self_crosses(points):
            count, depth = crossing_depth(points, positions[junctions[cell]], bs, shear)
            total += count
            maximum = max(maximum, depth)
    return total, maximum
