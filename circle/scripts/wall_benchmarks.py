"""Run the wall benchmarks and write ``circle/BENCHMARKS.md``.

    python circle/scripts/wall_benchmarks.py

Every table states the time step, film spacing, run duration, equilibrium
criterion and measured error.  Fixed-mesh results and results with remeshing
enabled are reported separately.
"""
import sys
import time
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parents[2]))

from circle import benchmarks as b                                     # noqa: E402

OUT = Path(__file__).resolve().parents[1] / "BENCHMARKS.md"


def fmt(value):
    if isinstance(value, bool):
        return "yes" if value else "no"
    if isinstance(value, float):
        return f"{value:.4g}"
    return str(value)


def table(rows, columns):
    lines = ["| " + " | ".join(header for header, _ in columns) + " |",
             "|" + "---|" * len(columns)]
    for row in rows:
        lines.append("| " + " | ".join(fmt(row[key]) for _, key in columns) + " |")
    return "\n".join(lines)


def main():
    start = time.time()
    out = ["# Wall benchmarks", "",
           "Generated by `python circle/scripts/wall_benchmarks.py`. All runs at zero activity",
           "unless stated. Forces are in the code's units: a node moves by `psi*dt*f`, with",
           "`T_eff = max(T, 0)` and `p_n = P0*(rho/A - 1)/sqrt(rho)`.", "",
           f"Equilibrium criterion for single cells: {b.CRITERION}. The residual nodal force is",
           "reported for information; film nodes on a frictionless wall keep sliding along it",
           "under third-order forces after shape and traction have converged.", ""]

    free = b.free_cell()
    out += ["## Free cell far from the wall (remeshing on)", "",
            "Reference: area of an isolated cell from `p_n = T_eff/r`.", "",
            table([free], [("dt", "dt"), ("spacing", "spacing"), ("time to equilibrium", "time"),
                           ("criterion met", "converged"), ("residual force", "residual"),
                           ("resampling events", "resample_events"),
                           ("wall reaction", "wall_reaction"), ("area", "area"),
                           ("reference", "reference_area"), ("relative error", "area_error")]),
            ""]

    columns = [("spacing", "spacing"), ("dt", "dt"), ("nodes", "nodes"),
               ("time to equilibrium", "time"), ("criterion met", "converged"),
               ("resampling events", "resample_events"), ("arrival steps", "arrival_steps"),
               ("integrated traction", "total"), ("reference", "reference"),
               ("relative error", "traction_error"),
               ("projection vs constraint", "projection_vs_constraint"),
               ("resultant / total", "resultant")]
    out += ["## Squeezed cell: integrated wall traction", "",
            "One cell with `rho = 1.5` in a disc of unit area. Reference:",
            "`2*pi*R_w*(p_n - T_eff/R_w)` with the cell's own polygon area. The resultant",
            "vanishes by symmetry in this case only.", "",
            "### Fixed mesh, every node on the wall from the start", "",
            table([b.squeezed_cell(s, remesh=False, start="on_wall") for s in b.SPACINGS], columns),
            "",
            "### Fixed mesh, cell grows onto the wall", "",
            "The node count stays that of the smaller initial cell, so the final spacing is",
            "about 1.4 times the nominal one. A row marked as not meeting the criterion gives",
            "the value at 400 tau_R: nodes are still sliding along the wall.", "",
            table([b.squeezed_cell(s, remesh=False, start="grow") for s in (0.15, 0.1, 0.075)],
                  columns), "",
            "### Remeshing enabled, cell grows onto the wall", "",
            "Films are resampled as the cell expands, which restores the nominal spacing and",
            "the fixed-mesh error of the on-wall start. A row marked as not meeting the",
            "criterion gives the value at 400 tau_R.", "",
            table([b.squeezed_cell(s, remesh=True, start="grow") for s in (0.15, 0.1, 0.075)],
                  columns), ""]

    detach = b.detaching_cell()
    out += ["## Detachment (remeshing on)", "",
            "A cell with `rho = 0.5` starts on the wall of a unit-area disc.", "",
            table([detach], [("dt", "dt"), ("spacing", "spacing"),
                             ("contacts at first step", "first_step_contacts"),
                             ("reaction at first step", "first_step_reaction"),
                             ("time to equilibrium", "time"), ("criterion met", "converged"),
                             ("final contacts", "final_contacts"),
                             ("largest r/R_w", "max_radius"), ("relative area error", "area_error")]),
            ""]

    projection = b.projection_vs_constraint()
    out += ["## Projection estimate vs continuous constraint (fixed mesh)", "",
            "16 cells, spacing 0.15, one step from a common state. The estimate",
            "`(x_projected - x_trial)/(M dt)` is compared with `max(0, f.n)` on nodes that",
            "were on the wall at the start of the step.", "",
            table(projection["rows"], [("dt", "dt"), ("contact nodes", "contacts"),
                                       ("largest nodal error", "max_error"),
                                       ("relative error of the sum", "relative_error")]), ""]

    three = b.three_cell_refinement(scales=(1, 2, 4, 8))
    out += ["## Three cells in partial contact (remeshing on)", "",
            "W = 1, rho = 1. Time step and spacing are refined together. Traction is averaged",
            "over the last fifth of the run; the criterion is that the two halves of that",
            "window agree to 2e-3. `transient dip` is the lowest instantaneous reaction over",
            "its mean during 15-30 tau_R, while films are still being resampled.", "",
            table(three["rows"][:1] + three["rows"][1:],
                  [("dt", "dt"), ("spacing", "spacing"), ("duration", "duration"),
                   ("window", "window"), ("mean reaction", "mean"),
                   ("criterion met", "converged"), ("window sd / mean", "intermittency"),
                   ("transient dip", "transient_dip"), ("resampling events", "resample_events"),
                   ("contact nodes", "contacts"), ("packing", "packing")]), "",
            "Relative change of the mean from one level to the next: "
            + ", ".join(fmt(row["change_from_coarser"]) for row in three["rows"][1:]) + ".",
            "The reaction in partial contact therefore converges more slowly than in full",
            "contact: at the default spacing 0.15 it is about 9% above the finest level.", ""]

    aware = b.three_cell_refinement(scales=(4,), wall_resample=True)["rows"][0]
    plain = three["rows"][2]
    active = b.resampling_effect_active()
    out += ["## Effect of resampling on wall contact", "",
            "A node created by resampling a wall-following film starts on the chord, slightly",
            "inside the wall, and carries no reaction until pressure returns it. The optional",
            "`wall_resample=True` places such nodes on the wall (off by default).", "",
            "Three cells, finest level above:", "",
            table([dict(mode="plain", **plain), dict(mode="wall-aware", **aware)],
                  [("resampling", "mode"), ("mean reaction", "mean"),
                   ("transient dip", "transient_dip"), ("window sd / mean", "intermittency")]), "",
            f"Active tissue ({active['n_cells']} cells, W = {active['w']}, rho = {active['rho']}, "
            f"mu = {active['mu']}), time-averaged reaction:", "",
            table(active["rows"], [("wall-aware", "wall_resample"), ("dt", "dt"),
                                   ("spacing", "spacing"), ("duration", "duration"),
                                   ("seeds", "seeds"), ("mean reaction", "mean"),
                                   ("standard error", "standard_error"),
                                   ("arrivals per step", "arrivals_per_step")]), ""]

    chord = b.chord_deficit()
    out += ["## Chord-area deficit of the initial tiling", "",
            "36 cells. Leading-order value for uniform sampling: `(spacing/R_w)^2 / 6`.", "",
            table(chord["rows"], [("spacing", "spacing"), ("1 - packing", "deficit"),
                                  ("deficit / (spacing/R_w)^2", "coefficient")]), ""]

    OUT.write_text("\n".join(out))
    print(f"wrote {OUT} in {time.time() - start:.0f} s")


if __name__ == "__main__":
    main()
